// Слова, которые убираем из своего пункта профиля, чтобы найти сам продукт:
// «Аллергия на киноа» → «киноа», «Не ем баклажаны» → «баклажаны».
var noise = map[string]bool{
	"аллергия": true, "на": true, "без": true, "не": true, "ем": true, "ест": true, "есть": true,
	"непереносимость": true, "нельзя": true, "нет": true, "аллергии": true, "кроме": true, "и": true, "или": true, "диета": true,
}

// stemsFor — запрещённые начала слов для пункта профиля. Для своих пунктов (их нет в списке)
// берём значимые слова пункта и отрезаем окончание: «баклажаны» → «баклажа», «соли» → «сол».
func stemsFor(pref string) []string {
	if stems, ok := forbidden[pref]; ok {
		return stems
	}
	var stems []string
	for _, w := range words(pref) {
		r := []rune(w)
		if noise[w] || len(r) < 3 {
			continue
		}
		switch {
		case len(r) >= 6:
			r = r[:len(r)-2]
		case len(r) >= 4:
			r = r[:len(r)-1]
		}
		stems = append(stems, string(r))
	}
	return stems
}

// words — слова текста в нижнем регистре, «ё» заменена на «е».
func words(text string) []string {
	text = strings.ReplaceAll(strings.ToLower(text), "ё", "е")
	return strings.FieldsFunc(text, func(r rune) bool { return !unicode.IsLetter(r) })
}

// violates — нарушает ли текст (название и ингредиенты блюда) пункт профиля.
func violates(pref string, text []string) bool {
	for _, stem := range stemsFor(pref) {
		stemWords := words(stem)
		for i := 0; i+len(stemWords) <= len(text); i++ {
			if matchesAt(text[i:], stemWords) {
				return true
			}
		}
	}
	return false
}

// matchesAt: каждое слово текста начинается с соответствующего слова основы
// («масло сливочное» совпадает с «масло сливочное», но не с «масло оливковое»).
func matchesAt(text, stem []string) bool {
	for j, s := range stem {
		// «Сырой» — характеристика продукта, а не молочный ингредиент «сыр».
		// «Сыром» само по себе остаётся запрещённым («посыпьте сыром»),
		// исключение — только устойчивое сочетание «в сыром виде».
		if s == "сыр" && rawAdjective(text[j:]) {
			return false
		}
		if !strings.HasPrefix(text[j], s) {
			return false
		}
	}
	return len(stem) > 0
}

func rawAdjective(text []string) bool {
	if len(text) == 0 {
		return false
	}
	switch text[0] {
	case "сырой", "сырая", "сырое", "сырые", "сырого", "сырому", "сырую", "сырым", "сырыми", "сырых":
		return true
	case "сыром":
		return len(text) > 1 && text[1] == "виде"
	}
	return false
}
