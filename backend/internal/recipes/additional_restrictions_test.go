package recipes

import "testing"

func TestAdditionalFoodRestrictions(t *testing.T) {
	cases := []struct{ pref, dish string }{
		{"Аллергия на миндаль", "Миндальное молоко"},
		{"Аллергия на фундук", "Паста с фундуком"},
		{"Аллергия на грецкие орехи", "Салат с грецкими орехами"},
		{"Аллергия на кешью", "Соус из кешью"},
		{"Аллергия на фисташки", "Фисташковый крем"},
		{"Аллергия на пекан", "Пирог с пеканом"},
		{"Аллергия на бразильские орехи", "Бразильские орехи"},
		{"Аллергия на кедровые орехи", "Песто с кедровыми орехами"},
		{"Аллергия на ракообразных", "Суп с креветками"},
		{"Аллергия на горох", "Гороховый суп"},
		{"Аллергия на чечевицу", "Чечевичный суп"},
		{"Аллергия на нут", "Фалафель с хумусом"},
		{"Аллергия на семена подсолнечника", "Семена подсолнечника"},
		{"Аллергия на гречку", "Гречневая каша"},
		{"Аллергия на овёс", "Овсяная каша"},
		{"Аллергия на рис", "Рисовая каша"},
		{"Аллергия на персики", "Персиковый пирог"},
		{"Аллергия на груши", "Грушевый десерт"},
		{"Аллергия на бананы", "Банановый смузи"},
		{"Аллергия на авокадо", "Салат с авокадо"},
		{"Аллергия на морковь", "Морковный салат"},
		{"Аллергия на картофель", "Картофельный суп"},
		{"Непереносимость сорбитола", "Десерт с сорбитолом"},
		{"Непереносимость маннитола", "Подсластитель маннитол"},
		{"Непереносимость ксилита", "Подсластитель ксилит"},
		{"Непереносимость полиолов", "Десерт с эритритом"},
	}
	for _, tc := range cases {
		t.Run(tc.pref, func(t *testing.T) {
			if _, ok := forbidden[tc.pref]; !ok {
				t.Fatal("missing explicit restriction rule")
			}
			if !violates(tc.pref, words(tc.dish)) {
				t.Fatalf("missed ingredient in %q", tc.dish)
			}
			if violates(tc.pref, words("Огуречный салат с укропом")) {
				t.Fatal("unrelated dish rejected")
			}
		})
	}
	if violates("Аллергия на миндаль", words("Каша с кешью")) {
		t.Fatal("specific nut restriction blocks every nut")
	}
	if violates("Аллергия на ракообразных", words("Кальмары с овощами")) {
		t.Fatal("crustaceans conflated with molluscs")
	}
}
