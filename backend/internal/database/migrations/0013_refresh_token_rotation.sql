-- Отличаем «токен обменяли на новый» (replaced_at) от «сессию завершили» (revoked_at).
--
-- Зачем: браузер может оборвать запрос обновления сессии (перезагрузили страницу) или
-- отправить его из двух вкладок сразу. Тогда сервер уже выдал новый токен, а браузер
-- снова присылает старый. Раньше это выглядело как кража токена и завершало все сессии.
-- Теперь старый токен ещё 30 секунд после обмена можно использовать повторно,
-- а позже повтор — по-прежнему признак кражи.
ALTER TABLE refresh_tokens ADD COLUMN replaced_at TIMESTAMPTZ;
