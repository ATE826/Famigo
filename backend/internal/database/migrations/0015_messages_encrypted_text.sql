-- Текст сообщений теперь хранится зашифрованным (см. internal/fieldcrypt): в колонке лежит
-- «enc:v1:<номер ключа>:<base64>», а шифртекст длиннее исходного (+ префикс, nonce, тег, base64).
-- Старое ограничение «не больше 2000 символов» относилось к открытому тексту и сломало бы запись.
--
-- Длину самого сообщения (1–2000 символов) по-прежнему проверяет сервер до шифрования.
-- Здесь остаётся запас с большим верхним пределом: 2000 символов — это до 8000 байт UTF-8,
-- после шифрования и base64 около 10 700 символов.
ALTER TABLE messages DROP CONSTRAINT IF EXISTS messages_text_check;
ALTER TABLE messages ADD CONSTRAINT messages_text_length CHECK (char_length(text) <= 20000);
